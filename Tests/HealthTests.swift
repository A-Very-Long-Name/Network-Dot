import Foundation

@main
struct HealthTests {
    static func main() {
        var health = ConnectivityHealth()
        health.reset(connected: false, now: 100)
        assert(health.state(now: 100) == .offline, "Link loss must be immediate")
        health.reset(connected: true, now: 101)
        assert(health.state(now: 101) == .checking)
        assert(health.state(now: 102.99) == .checking)
        assert(health.state(now: 103) == .offline, "First probe grace must end at 2 seconds")
        health.succeeded(now: 103.1)
        assert(health.state(now: 103.1) == .online, "Recovery must be immediate")
        assert(health.state(now: 105.09) == .online)
        assert(health.state(now: 105.1) == .offline, "Stale success must expire")
        health.succeeded(now: 105.2)
        assert(health.state(now: 105.2) == .online, "One successful target is sufficient")
        health.reset(connected: true, now: 106)
        assert(health.state(now: 106) == .checking, "Network change must clear previous success")
        health.reset(connected: false, now: 106.1)
        assert(health.state(now: 106.1) == .offline)
        var round = ProbeRound(count: 3, primary: 0)
        assert(round.start() == [0], "Healthy round must start only Apple")
        assert(round.complete(index: 0, success: true) == .winner(0))
        assert(round.fallback().isEmpty, "Successful Apple must suppress backups")
        assert(round.complete(index: 0, success: false) == .ignored, "Late callbacks must be ignored")
        var failedPrimary = ProbeRound(count: 3, primary: 0)
        assert(failedPrimary.start() == [0])
        assert(failedPrimary.complete(index: 0, success: false) == .startFallback)
        assert(failedPrimary.fallback() == [1, 2])
        assert(failedPrimary.fallback().isEmpty, "Backups must not launch twice")
        assert(failedPrimary.complete(index: 1, success: true) == .winner(1))
        assert(failedPrimary.complete(index: 2, success: true) == .ignored)
        var slowPrimary = ProbeRound(count: 3, primary: 0)
        assert(slowPrimary.start() == [0])
        assert(slowPrimary.fallback() == [1, 2], "Slow primary must allow hedged backup probes")
        assert(slowPrimary.complete(index: 1, success: false) == .waiting)
        assert(slowPrimary.complete(index: 0, success: true) == .winner(0))
        var allFail = ProbeRound(count: 3, primary: 1)
        assert(allFail.start() == [1])
        assert(allFail.complete(index: 1, success: false) == .startFallback)
        assert(allFail.fallback() == [0, 2])
        assert(allFail.complete(index: 0, success: false) == .waiting)
        assert(allFail.complete(index: 2, success: false) == .allFailed)
        var onlyOne = ProbeRound(count: 1, primary: 0)
        assert(onlyOne.start() == [0])
        assert(onlyOne.fallback().isEmpty)
        assert(onlyOne.complete(index: 0, success: false) == .allFailed)
        var selection = ProbeSelection()
        assert(selection.primary(now: 100, count: 3) == 0)
        selection.launched(index: 0, now: 100)
        selection.succeeded(index: 1)
        assert(selection.primary(now: 159.9, count: 3) == 1, "Remember reachable backup")
        assert(selection.primary(now: 160, count: 3) == 0, "Retry Apple once a minute")
        selection.launched(index: 0, now: 160)
        assert(selection.primary(now: 161, count: 3) == 1, "Do not repeatedly retry blocked Apple")
        selection.succeeded(index: 0)
        assert(selection.primary(now: 162, count: 3) == 0, "Return to Apple after recovery")
        selection.reset()
        assert(selection.primary(now: 162, count: 3) == 0)
        print("Probe policy tests passed (one healthy request, failover, slow primary, cancellation, Apple retry).")
        print("Connectivity health tests passed (2-second timeout, immediate link loss/recovery, network changes).")
    }
}
